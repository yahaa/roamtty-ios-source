import Foundation

@main enum TerminalInteractionChecks {
    static func main() {
        for value in ["│ ❯ /model Grok 4.7 │", "› /review", "│ > /help │", "> /", "❯ /compact", "$ /usr/bin/env"] {
            precondition(TerminalCursorControls.startsWithSlash(value), value)
        }
        for value in ["│ ❯ fix the /tmp path │", "› ", "", "v@dev:~/work$ /bin/ls", "➜ roamtty git:(main) /x", ">/no-space", "Enter:send │ Alt+Enter:newline │"] {
            precondition(!TerminalCursorControls.startsWithSlash(value), value)
        }
        var state = TerminalCursorControls()
        precondition(state.key(at: 0) == .escape)
        state.typed(at: 10)
        precondition(state.key(at: 10.69) == .escape)
        precondition(state.key(at: 10.7) == .enter)
        precondition(state.key(at: 13.7) == .escape)
        state.observe(row: "› /review")
        precondition(state.onSlashLine && state.key(at: 20) == .escape)
        state.wake(at: 20)
        precondition(state.key(at: 20) == .enter)
        state.observe(row: "› /review commit")
        precondition(state.onSlashLine && state.key(at: 23) == .escape)
        state.observe(row: "› ")
        precondition(!state.onSlashLine)
        state.observe(row: "› /model")
        precondition(state.onSlashLine)
        precondition(TerminalCursorControls.tapHitsCursor(y: 60, rowTop: 100, rowHeight: 20, viewportHeight: 400))
        precondition(!TerminalCursorControls.tapHitsCursor(y: 59, rowTop: 100, rowHeight: 20, viewportHeight: 400))
        precondition(!TerminalCursorControls.tapHitsCursor(y: 160, rowTop: 100, rowHeight: 20, viewportHeight: 400))
        precondition(TerminalCursorControls.tapHitsCursor(y: 63, rowTop: 0, rowHeight: 8, viewportHeight: 400))
        precondition(!TerminalCursorControls.tapHitsCursor(y: 64, rowTop: 0, rowHeight: 8, viewportHeight: 400))
        precondition(!TerminalCursorControls.tapHitsCursor(y: 0, rowTop: -30, rowHeight: 20, viewportHeight: 400))
        precondition(!TerminalCursorControls.tapHitsCursor(y: 399, rowTop: 400, rowHeight: 20, viewportHeight: 400))
        let old = TerminalStartupGate.clients(from: "login banner\n__ROAMTTY_CLIENT__12|/dev/pts/2\n")
        let new = TerminalStartupGate.clients(from: "__ROAMTTY_CLIENT__13|/dev/pts/3\n")
        precondition(old == ["12|/dev/pts/2"])
        precondition(TerminalStartupGate.clients(from: "error\n__ROAMTTY_CLIENT__oops|/dev/pts/2\n").isEmpty)
        var gate = TerminalStartupGate(needsTmuxClient: true, requiresOutput: true, previousClients: old)
        gate.observe(clients: old); gate.sawOutput = true
        precondition(!gate.ready, "An older attached client cannot authorize startup")
        gate.observe(clients: new)
        precondition(gate.ready)
        var beforeOutput = TerminalStartupGate(needsTmuxClient: true, requiresOutput: true, previousClients: [])
        beforeOutput.observe(clients: new)
        precondition(!beforeOutput.ready, "tmux attachment alone cannot authorize startup before output")
        var moshShell = TerminalStartupGate(needsTmuxClient: false, requiresOutput: true, previousClients: [])
        precondition(!moshShell.ready); moshShell.sawOutput = true; precondition(moshShell.ready)
        precondition(TerminalStartupGate(needsTmuxClient: false, requiresOutput: false, previousClients: []).ready)
        var toolbox = TerminalToolboxState()
        toolbox.wake(at: 0); toolbox.expire(at: 4.99)
        precondition(toolbox.ghostVisible)
        toolbox.expire(at: 5)
        precondition(!toolbox.ghostVisible)
        toolbox.workspaceTouch(at: 6); precondition(toolbox.ghostVisible)
        toolbox.beginRing(at: 7); toolbox.expire(at: 30)
        precondition(toolbox.ringOpen && toolbox.ghostVisible, "Holding the ring outlives the ghost timeout")
        toolbox.pinRing(at: 31); toolbox.expire(at: 34.99); precondition(toolbox.ringOpen)
        toolbox.expire(at: 35); precondition(!toolbox.ringOpen && !toolbox.ghostVisible)
        toolbox.wake(at: 40); toolbox.openDock(at: 40); toolbox.workspaceTouch(at: 41)
        precondition(!toolbox.dockVisible && toolbox.ghostVisible, "An outside touch collapses a floating dock")
        toolbox.setPinned(true, at: 42); toolbox.workspaceTouch(at: 50); toolbox.expire(at: 100)
        precondition(toolbox.dockVisible && toolbox.pinned, "Pinned tools do not auto-hide or collapse on terminal touch")
        precondition(TerminalDockGeometry.twoColumns(landscape: true, keyboardVisible: false, height: 328))
        precondition(!TerminalDockGeometry.twoColumns(landscape: true, keyboardVisible: true, height: 328))
        let size = CGSize(width: 390, height: 600)
        let dock = TerminalDockGeometry.frame(viewport: size, content: CGSize(width: 48, height: 48))
        precondition(abs(dock.midY - 600 * 0.382) < 0.01 && dock.maxX == 382)
        let cursor = CGRect(x: 350, y: dock.midY - 16, width: 40, height: 32)
        let moved = TerminalDockGeometry.frame(viewport: size, content: CGSize(width: 48, height: 48), avoiding: cursor)
        precondition(!moved.intersects(cursor.insetBy(dx: -4, dy: -4)), "The ghost must leave the cursor-row control tappable")
        let short = TerminalDockGeometry.frame(viewport: CGSize(width: 390, height: 90), content: CGSize(width: 48, height: 400))
        precondition(short.minY >= 4 && short.maxY <= 86)
        precondition(TerminalPaste.needsConfirmation("a\nb", bracketed: false))
        precondition(TerminalPaste.needsConfirmation("a\rb", bracketed: false))
        precondition(!TerminalPaste.needsConfirmation("a\nb", bracketed: true))
        precondition(!TerminalPaste.needsConfirmation("a\tb", bracketed: false))
        // swiftlint:disable:next force_try - a failure here is the check failing
        precondition(try! TerminalPaste.input("a\r\nb\nc\rd\t\u{1b}[201~\u{3}\u{7f}\u{85}", bracketed: true) == "\u{1b}[200~a\rb\rc\rd\t[201~\u{1b}[201~")
        do { _ = try TerminalPaste.input(String(repeating: "x", count: 131_073), bracketed: false); preconditionFailure("Oversize paste must be rejected") } catch { }
        var capture = TerminalPasteCapture(bracketed: true)
        capture.append(Array("\u{1b}[200~hi\u{1b}[201~".utf8))
        precondition(capture.text == "hi" && !capture.tooLarge)
        var plain = TerminalPasteCapture(bracketed: false)
        precondition(plain.text == nil)
        plain.append([UInt8](repeating: 120, count: TerminalPaste.byteLimit + 13))
        precondition(plain.tooLarge && plain.text == nil)
        precondition(TerminalKeys.arrow("D", applicationCursor: false, control: false, shift: false) == "\u{1b}[D")
        precondition(TerminalKeys.arrow("C", applicationCursor: true, control: false, shift: false) == "\u{1b}OC")
        precondition(TerminalKeys.arrow("D", applicationCursor: true, control: false, shift: true) == "\u{1b}[1;2D")
        precondition(TerminalKeys.arrow("A", applicationCursor: false, control: true, shift: true) == "\u{1b}[1;6A")
        precondition(TerminalKeys.function(1, control: false, shift: false) == "\u{1b}OP")
        precondition(TerminalKeys.function(1, control: false, shift: true) == "\u{1b}[1;2P")
        precondition(TerminalKeys.function(12, control: true, shift: false) == "\u{1b}[24;5~")
        precondition(TerminalKeys.function(13, control: false, shift: false) == nil)
        precondition(TerminalKeys.swipeDirection(x: -32, y: 10) == -1)
        precondition(TerminalKeys.swipeDirection(x: 32, y: -10) == 1)
        precondition(TerminalKeys.swipeDirection(x: 31.9, y: 0) == nil)
        precondition(TerminalKeys.swipeDirection(x: 45, y: 30) == nil, "Vertical/diagonal scrolling must not emit cursor keys")
        precondition(TerminalScrolling.disposition(connected: true, selecting: false, mouseTracking: true, alternate: true) == .wheel)
        precondition(TerminalScrolling.disposition(connected: true, selecting: false, mouseTracking: false, alternate: true) == .arrows)
        precondition(TerminalScrolling.disposition(connected: true, selecting: false, mouseTracking: false, alternate: false) == .local)
        precondition(TerminalScrolling.disposition(connected: true, selecting: true, mouseTracking: true, alternate: true) == .ignored)
        precondition(TerminalScrolling.disposition(connected: false, selecting: false, mouseTracking: true, alternate: true) == .ignored)
        precondition(TerminalScrolling.mouseButton(rowsDown: -1) == 4 && TerminalScrolling.mouseButton(rowsDown: 1) == 5)
        let mouse = TerminalScrolling.mousePoint(CGPoint(x: 45, y: 50), cell: CGSize(width: 10, height: 20), columns: 80, rows: 24)
        precondition(mouse.column == 4 && mouse.row == 2 && mouse.pixelX == 46 && mouse.pixelY == 51)
        let outside = TerminalScrolling.mousePoint(CGPoint(x: 9999, y: -1), cell: CGSize(width: 8, height: 16), columns: 400, rows: 24)
        precondition(outside.column == 222 && outside.row == 0 && outside.pixelX == 3200 && outside.pixelY == 1)
        var scroll = TerminalScrollAccumulator()
        precondition(scroll.rowsDown(translationY: 9, rowHeight: 20) == 0)
        precondition(scroll.rowsDown(translationY: 21, rowHeight: 20) == -1, "Downward dragging requests older history")
        precondition(scroll.rowsDown(translationY: 39, rowHeight: 20) == 0)
        precondition(scroll.rowsDown(translationY: 40, rowHeight: 20) == -1)
        precondition(scroll.rowsDown(translationY: 0, rowHeight: 20) == 2, "Direction reversal scrolls forward")
        scroll.reset(); precondition(scroll.rowsDown(translationY: -20, rowHeight: 20) == 1)
        print("Terminal checks passed: cursor/startup, toolbox placement/timeouts, paste, modified keys and local/remote scrolling")
    }
}
